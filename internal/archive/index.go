package archive

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const generatedNote = "<!-- Generated by devopspadcli archive index. Do not edit; archive commit regenerates it. -->\n"

// RenderIndex renders INDEX.md: a matrix overview for browsing the archive on
// a Git host. It contains no dates relative to today, so it only changes when
// the archive changes.
func (a *Archive) RenderIndex() []byte {
	var b bytes.Buffer
	cell := func(s []string) string {
		if len(s) == 0 {
			return "-"
		}
		return strings.Join(s, ", ")
	}
	esc := func(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
	b.WriteString(generatedNote)
	title := a.Root.Metadata.Title
	if title == "" {
		title = a.Root.Metadata.Name
	}
	fmt.Fprintf(&b, "\n# %s\n\n", esc(title))
	b.WriteString("## Products\n\n| Product | Stage | Services | Domains | Environments | Hosts |\n| --- | --- | --- | --- | --- | --- |\n")
	matrix, _ := a.Matrix("", "")
	for _, m := range matrix {
		name := m.Product
		if m.Title != "" {
			name = m.Title
		}
		fmt.Fprintf(&b, "| [%s](products/%s/product.yaml) | %s | %s | %s | %s | %s |\n", esc(name), m.Product, m.Stage, cell(m.Services), cell(m.Domains), cell(m.Environments), cell(m.Hosts))
	}
	for _, k := range kinds {
		if k.Dir == "" {
			continue
		}
		list, _ := a.List(k.Kind, "")
		if len(list) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n", k.Kind)
		header, _ := Summary(list[0])
		fmt.Fprintf(&b, "| %s | USED BY |\n|%s\n", strings.Join(header, " | "), strings.Repeat(" --- |", len(header)+1))
		for _, r := range list {
			_, row := Summary(r)
			row[0] = fmt.Sprintf("[%s](%s)", row[0], r.File)
			for i := 1; i < len(row); i++ {
				row[i] = esc(row[i])
			}
			used := a.UsedBy(r.Ref)
			for i := range used {
				used[i] = strings.TrimPrefix(used[i], "product:")
			}
			fmt.Fprintf(&b, "| %s | %s |\n", strings.Join(row, " | "), cell(used))
		}
	}
	if rows := a.Renewals(nowUTC(), -1); len(rows) > 0 {
		b.WriteString("\n## Renewals\n\n| Due | What | Ref | Auto | Cost |\n| --- | --- | --- | --- | --- |\n")
		for _, r := range rows {
			auto := "-"
			if r.AutoRenew != nil {
				auto = map[bool]string{true: "yes", false: "no"}[*r.AutoRenew]
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.Due, esc(r.What), r.Ref, auto, cell(nonEmpty(r.Cost)))
		}
	}
	return b.Bytes()
}

func nonEmpty(s string) []string {
	if s == "" {
		return nil
	}
	return []string{s}
}

// RenderAgents renders AGENTS.md, the entry point for AI agents without the skill.
func (a *Archive) RenderAgents() []byte {
	return []byte(generatedNote + `
# DevOpsPad archive: ` + a.Root.Metadata.Name + `

This Git repository is a DevOpsPad archive (protocol ` + APIVersion + `). It records every
product, service, environment, host, cluster, domain, datastore and third-party account of
an OPC product matrix. It holds secret references, never secret values.

Use the devopspad skill. Without it, run ` + "`devopspadcli skill print`" + ` and follow it. Rules:

- Read with ` + "`devopspadcli get|describe|refs|report`" + `; field definitions: ` + "`devopspadcli schema <kind>`" + `.
- After editing YAML run ` + "`devopspadcli archive validate -o json`" + ` until it passes, then
  ` + "`devopspadcli archive commit -m \"<type>(<ref>): <summary>\" --actor ai/<name>`" + `.
- Never write passwords, tokens or keys. Store them with ` + "`devopspadcli secrets set keychain:<account>`" + `
  and reference them as keychain:<account>, env:<NAME> or file:<path>.
- Never edit records/, INDEX.md or AGENTS.md by hand. .devopspad/ is local state and is not committed.
`)
}

// WriteGenerated refreshes INDEX.md and AGENTS.md.
func WriteGenerated(a *Archive) error {
	for name, b := range map[string][]byte{"INDEX.md": a.RenderIndex(), "AGENTS.md": a.RenderAgents()} {
		p := filepath.Join(a.Dir, name)
		if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, b) {
			continue
		}
		if err := writeAtomic(p, b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func (a *Archive) checkIgnore() {
	if !gitignored(a.Dir) {
		a.warnf(".gitignore", 0, "", "layout.gitignore", ".gitignore must contain .devopspad/ so local scan results and state are never committed")
	}
}

func (a *Archive) checkIndex() {
	for name, b := range map[string][]byte{"INDEX.md": a.RenderIndex(), "AGENTS.md": a.RenderAgents()} {
		if old, err := os.ReadFile(filepath.Join(a.Dir, name)); err != nil || !bytes.Equal(old, b) {
			a.warnf(name, 0, "", "generated.stale", "%s is out of date; archive commit regenerates it (or run devopspadcli archive index)", name)
		}
	}
}
